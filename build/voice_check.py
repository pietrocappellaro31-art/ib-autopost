"""
Check a voiceover against its script before it goes in a Reel: transcribe the
audio with a local speech recogniser (Moonshine tiny, through sherpa-onnx) and
compare the words. A cloned voice is generated by a language model and can
drop, repeat or swap a word; this catches it. Kokoro (phoneme-driven) rarely
does, so this matters most for voice_clone.CloneVoice.

    python build/voice_check.py audio.wav "the script it should say"

Files (not in the repo): $SHERPA_DIR as in voice_clone.py, $MOONSHINE_DIR the
folder sherpa-onnx-moonshine-tiny-en-int8 (sherpa-onnx releases, asr-models).
"""

import os
import pathlib
import re
import subprocess
import sys
import tempfile

import numpy as np

SHERPA = os.environ.get("SHERPA_DIR", "")
MOON = os.environ.get("MOONSHINE_DIR", "")

ONES = {w: i for i, w in enumerate("zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen "
                                    "fifteen sixteen seventeen eighteen nineteen".split())}
TENS = {w: 10 * i for i, w in enumerate("_ _ twenty thirty forty fifty sixty seventy eighty ninety".split()) if w != "_"}


def words(text):
    """Lower-case words with every number, spelled or in digits, as one
    canonical token ("seven and a half" and "7.5" both become "7.5")."""
    t = text.lower().replace("%", " percent ").replace("-", " ").replace(",", " ")
    toks = re.findall(r"\d+(?:\.\d+)?|[a-z']+", t)
    out, i = [], 0
    while i < len(toks):
        w = toks[i]
        if re.fullmatch(r"\d+(?:\.\d+)?", w):
            out.append(str(float(w)).rstrip("0").rstrip("."))
            i += 1
            continue
        n, j = None, i
        if w == "a" and i + 1 < len(toks) and toks[i + 1] == "hundred":
            n, j = 100, i + 2
        elif w in ONES or w in TENS:
            n, j = 0, i
            if toks[j] in TENS:
                n += TENS[toks[j]]
                j += 1
                if j < len(toks) and toks[j] in ONES and ONES[toks[j]] < 10:
                    n += ONES[toks[j]]
                    j += 1
            elif toks[j] in ONES:
                n += ONES[toks[j]]
                j += 1
            if j < len(toks) and toks[j] == "hundred":
                n *= 100
                j += 1
        if n is not None:
            if toks[j:j + 3] == ["and", "a", "half"]:
                n += .5
                j += 3
            out.append(str(float(n)).rstrip("0").rstrip("."))
            i = j
            continue
        out.append(w)
        i += 1
    return out


def transcribe(wav_path):
    b = pathlib.Path(SHERPA)
    m = pathlib.Path(MOON)
    with tempfile.TemporaryDirectory() as d:
        w16 = pathlib.Path(d) / "a.wav"
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", str(wav_path), "-ac", "1", "-ar", "16000", str(w16)], check=True)
        r = subprocess.run([str(b / "bin" / "sherpa-onnx-offline"), f"--moonshine-preprocessor={m / 'preprocess.onnx'}",
                            f"--moonshine-encoder={m / 'encode.int8.onnx'}",
                            f"--moonshine-uncached-decoder={m / 'uncached_decode.int8.onnx'}",
                            f"--moonshine-cached-decoder={m / 'cached_decode.int8.onnx'}", f"--tokens={m / 'tokens.txt'}",
                            "--num-threads=2", str(w16)],
                           env={**os.environ, "LD_LIBRARY_PATH": str(b / "lib")}, capture_output=True, text=True, check=True)
    out = r.stdout + r.stderr
    hits = re.findall(r'"text":\s*"([^"]*)"', out)
    return hits[-1].strip() if hits else ""


def wer(ref, hyp):
    r, h = words(ref), words(hyp)
    d = np.zeros((len(r) + 1, len(h) + 1), int)
    d[:, 0] = range(len(r) + 1)
    d[0, :] = range(len(h) + 1)
    for i in range(1, len(r) + 1):
        for j in range(1, len(h) + 1):
            d[i, j] = min(d[i - 1, j] + 1, d[i, j - 1] + 1, d[i - 1, j - 1] + (r[i - 1] != h[j - 1]))
    return d[len(r), len(h)] / max(len(r), 1)


def check(wav_path, script, limit=.12):
    heard = transcribe(wav_path)
    e = wer(script, heard)
    return e <= limit, e, heard


if __name__ == "__main__":
    ok, e, heard = check(sys.argv[1], sys.argv[2])
    print(("OK  " if ok else "BAD ") + f"WER {e:.0%}  heard: {heard}")
